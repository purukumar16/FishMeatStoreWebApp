export function generateVariants(
  basePriceKg: number,
  basePieces1kg: [number, number],
  cutLabel: string,
  netGrossRatio = 0.85
): Record<WeightVariant, ProductVariantInfo> {
  const formatPieces = (min: number, max: number) => (min === max ? `${min} pcs` : `${min}-${max} pcs`);

  return {
    '250g': {
      weight: '250g',
      price: Math.round(basePriceKg * 0.28), // realistic slight packaging premium
      serves: 'Serves 1',
      pieces: formatPieces(Math.max(1, Math.round(basePieces1kg[0] * 0.25)), Math.max(2, Math.round(basePieces1kg[1] * 0.25))),
      netWeight: '250g',
      grossWeight: `${Math.round(250 / netGrossRatio)}g`,
    },
    '500g': {
      weight: '500g',
      price: Math.round(basePriceKg * 0.52),
      serves: 'Serves 2-3',
      pieces: formatPieces(Math.round(basePieces1kg[0] * 0.5), Math.round(basePieces1kg[1] * 0.5)),
      netWeight: '500g',
      grossWeight: `${Math.round(500 / netGrossRatio)}g`,
    },
    '750g': {
      weight: '750g',
      price: Math.round(basePriceKg * 0.76),
      serves: 'Serves 3-4',
      pieces: formatPieces(Math.round(basePieces1kg[0] * 0.75), Math.round(basePieces1kg[1] * 0.75)),
      netWeight: '750g',
      grossWeight: `${Math.round(750 / netGrossRatio)}g`,
    },
    '1kg': {
      weight: '1kg',
      price: basePriceKg,
      serves: 'Serves 4-5',
      pieces: formatPieces(basePieces1kg[0], basePieces1kg[1]),
      netWeight: '1000g',
      grossWeight: `${Math.round(1000 / netGrossRatio)}g`,
    },
  };
}

